    [Fact]
    public async Task Manager_CanCompleteWorkOrder_AutomaticallyYieldsBranchInventoryAndStockMovement()
    {
        var (db, tenantContext, userService, manufacturingService) = SetupTestEnvironment();
        var tenantId = Guid.NewGuid();

        tenantContext.SetContext(tenantId, "mgr-1", TenantRole.Manager);
        userService.UserId = "mgr-1";

        var branch = new Branch { Id = Guid.NewGuid(), TenantId = tenantId, Name = "Berlin Plant" };
        var product = new Product { Id = Guid.NewGuid(), TenantId = tenantId, Sku = "BAT-LITH-48V", Name = "Lithium Battery 48V", Category = ProductCategory.FinishedGoods };
        db.Branches.Add(branch);
        db.Products.Add(product);
        await db.SaveChangesAsync();

        var wo = await manufacturingService.CreateWorkOrderAsync(new CreateWorkOrderRequest
        {
            ProductId = product.Id,
            BranchId = branch.Id,
            QuantityTarget = 50m
        });

        // Complete the work order with 48 units actually produced (e.g. 2 scrap)
        var completed = await manufacturingService.UpdateWorkOrderStatusAsync(wo.Id, new UpdateWorkOrderStatusRequest
        {
            Status = WorkOrderStatus.Completed,
            QuantityProduced = 48m,
            Notes = "Completed with 2 units scrap loss"
        });

        completed.Status.Should().Be(WorkOrderStatus.Completed);
        completed.QuantityProduced.Should().Be(48m);
        completed.CompletedDateUtc.Should().NotBeNull();

        // Verify that Branch Inventory now reflects the produced units
        var inventory = await db.ProductInventories
            .FirstOrDefaultAsync(pi => pi.ProductId == product.Id && pi.BranchId == branch.Id);

        inventory.Should().NotBeNull();
        inventory!.QuantityOnHand.Should().Be(48m);

        // Verify that an immutable StockMovement was recorded
        var movement = await db.StockMovements
            .FirstOrDefaultAsync(sm => sm.ProductId == product.Id && sm.BranchId == branch.Id);

        movement.Should().NotBeNull();
        movement!.Quantity.Should().Be(48m);
        movement.Type.Should().Be(StockMovementType.Receipt);
        movement.ReferenceNumber.Should().Be(wo.OrderNumber);
    }

