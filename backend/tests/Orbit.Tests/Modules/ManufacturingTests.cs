        var branch = new Branch { Id = Guid.NewGuid(), TenantId = tenantId, Name = "Plant" };
        var product = new Product { Id = Guid.NewGuid(), TenantId = tenantId, Sku = "SKU-TEST", Name = "Test Good", Category = ProductCategory.FinishedGoods };
        db.Branches.Add(branch);
        db.Products.Add(product);
        await db.SaveChangesAsync();

        var wo = await manufacturingService.CreateWorkOrderAsync(new CreateWorkOrderRequest
        {
            ProductId = product.Id,
            BranchId = branch.Id,
            QuantityTarget = 10m
        });

        await manufacturingService.UpdateWorkOrderStatusAsync(wo.Id, new UpdateWorkOrderStatusRequest
        {
            Status = WorkOrderStatus.Completed
