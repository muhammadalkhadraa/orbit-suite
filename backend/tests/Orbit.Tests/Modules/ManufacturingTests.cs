    [Fact]
    public async Task TenantIsolation_WorkOrdersAndBoms_NotVisibleAcrossTenants()
    {
        var (db, tenantContext, userService, manufacturingService) = SetupTestEnvironment();
        var tenantA = Guid.NewGuid();
        var tenantB = Guid.NewGuid();

        // Tenant A creates a work order and BOM
        tenantContext.SetContext(tenantA, "admin-a", TenantRole.Admin);
        userService.UserId = "admin-a";

        var branchA = new Branch { Id = Guid.NewGuid(), TenantId = tenantA, Name = "Plant A" };
        var productA = new Product { Id = Guid.NewGuid(), TenantId = tenantA, Sku = "SKU-A", Name = "Product A", Category = ProductCategory.FinishedGoods };
        db.Branches.Add(branchA);
        db.Products.Add(productA);
        await db.SaveChangesAsync();

        var woA = await manufacturingService.CreateWorkOrderAsync(new CreateWorkOrderRequest
        {
            ProductId = productA.Id,
            BranchId = branchA.Id,
            QuantityTarget = 100m
        });

        var bomA = await manufacturingService.CreateBomAsync(new CreateBomRequest
        {
            ProductId = productA.Id,
            Name = "BOM A"
        });

        // Switch to Tenant B
        tenantContext.SetContext(tenantB, "admin-b", TenantRole.Admin);
        userService.UserId = "admin-b";

        var listB = await manufacturingService.GetWorkOrdersAsync(new WorkOrderFilterRequest());
        listB.Data.Should().BeEmpty();

        var bomsB = await manufacturingService.GetBillsOfMaterialsAsync();
        bomsB.Should().BeEmpty();

        // Attempting to query Tenant A's work order by ID throws NotFoundException
        var actWo = async () => await manufacturingService.GetWorkOrderByIdAsync(woA.Id);
        await actWo.Should().ThrowAsync<NotFoundException>();

        var actBom = async () => await manufacturingService.GetBomByIdAsync(bomA.Id);
        await actBom.Should().ThrowAsync<NotFoundException>();
    }
