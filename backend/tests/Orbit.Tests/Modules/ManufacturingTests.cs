    [Fact]
    public async Task Admin_CanCreateWorkOrder_WithAutoGeneratedNumber_AndDraftStatus()
    {
        var (db, tenantContext, userService, manufacturingService) = SetupTestEnvironment();
        var tenantId = Guid.NewGuid();

        tenantContext.SetContext(tenantId, "admin-1", TenantRole.Admin);
        userService.UserId = "admin-1";

        var branch = new Branch { Id = Guid.NewGuid(), TenantId = tenantId, Name = "Austin Advanced Manufacturing Plant" };
        var product = new Product { Id = Guid.NewGuid(), TenantId = tenantId, Sku = "TITAN-DRONE-X1", Name = "Titan Drone X1", Category = ProductCategory.FinishedGoods };
        db.Branches.Add(branch);
        db.Products.Add(product);
        await db.SaveChangesAsync();

        var request = new CreateWorkOrderRequest
        {
            ProductId = product.Id,
            BranchId = branch.Id,
            QuantityTarget = 25m,
            Priority = WorkOrderPriority.High,
            Notes = "Batch 101 production run"
        };

        var workOrder = await manufacturingService.CreateWorkOrderAsync(request);

        workOrder.Should().NotBeNull();
        workOrder.OrderNumber.Should().StartWith("WO-");
        workOrder.Status.Should().Be(WorkOrderStatus.Draft);
        workOrder.Priority.Should().Be(WorkOrderPriority.High);
        workOrder.QuantityTarget.Should().Be(25m);
        workOrder.QuantityProduced.Should().Be(0m);
        workOrder.ProductName.Should().Be("Titan Drone X1");
        workOrder.BranchName.Should().Be("Austin Advanced Manufacturing Plant");
    }

    [Fact]
    public async Task Admin_CanCreateBom_WithMultipleComponentItems()
    {
        var (db, tenantContext, userService, manufacturingService) = SetupTestEnvironment();
        var tenantId = Guid.NewGuid();

        tenantContext.SetContext(tenantId, "admin-1", TenantRole.Admin);
        userService.UserId = "admin-1";

        var finishedGood = new Product { Id = Guid.NewGuid(), TenantId = tenantId, Sku = "SOLAR-INV-500", Name = "Solar Inverter 500W", Category = ProductCategory.FinishedGoods };
        var component1 = new Product { Id = Guid.NewGuid(), TenantId = tenantId, Sku = "CHIP-MCU-32", Name = "MCU 32-bit", Category = ProductCategory.Components };
        var component2 = new Product { Id = Guid.NewGuid(), TenantId = tenantId, Sku = "CAP-ELEC-470", Name = "Capacitor 470uF", Category = ProductCategory.Components };
        db.Products.AddRange(finishedGood, component1, component2);
        await db.SaveChangesAsync();

        var request = new CreateBomRequest
        {
            ProductId = finishedGood.Id,
            Name = "Solar Inverter BOM v1.0",
            Description = "Standard production bill of materials",
            Version = "v1.0",
            Items = new List<CreateBomItemRequest>
            {
                new() { ComponentProductId = component1.Id, QuantityRequired = 2m, UnitOfMeasure = "pcs" },
                new() { ComponentProductId = component2.Id, QuantityRequired = 8m, UnitOfMeasure = "pcs" }
            }
        };

        var bom = await manufacturingService.CreateBomAsync(request);

        bom.Should().NotBeNull();
        bom.BomNumber.Should().StartWith("BOM-");
        bom.Name.Should().Be("Solar Inverter BOM v1.0");
        bom.ProductName.Should().Be("Solar Inverter 500W");
        bom.Items.Should().HaveCount(2);
        bom.Items[0].QuantityRequired.Should().Be(2m);
        bom.Items[1].QuantityRequired.Should().Be(8m);
    }

