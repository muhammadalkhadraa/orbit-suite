    [Fact]
    public async Task Employee_CanSubmitLeaveRequest_WithAutoGeneratedNumber_AndPendingStatus()
    {
        var (db, tenantContext, userService, hrService) = SetupTestEnvironment();
        var tenantId = Guid.NewGuid();

        tenantContext.SetContext(tenantId, "user-emp-1", TenantRole.Employee);
        userService.UserId = "user-emp-1";

        var emp = new EmployeeProfile
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            UserId = "user-emp-1",
            EmployeeNumber = "EMP-001",
            FirstName = "Alice",
            LastName = "Smith",
            JobTitle = "Product Designer"
        };
        db.Employees.Add(emp);
        await db.SaveChangesAsync();

        var request = new CreateLeaveRequestRequest
        {
            LeaveType = LeaveType.Annual,
            StartDateUtc = DateTime.UtcNow.Date.AddDays(7),
            EndDateUtc = DateTime.UtcNow.Date.AddDays(9),
            DaysCount = 3,
            Reason = "Family vacation"
        };

        var leave = await hrService.SubmitLeaveRequestAsync(request);

        leave.Should().NotBeNull();
        leave.RequestNumber.Should().StartWith("LR-");
        leave.Status.Should().Be(LeaveStatus.Pending);
        leave.DaysCount.Should().Be(3);
        leave.EmployeeName.Should().Be("Alice Smith");
        leave.Reason.Should().Be("Family vacation");
    }

    [Fact]
    public async Task Employee_CanOnlyViewOwnLeaveRequests()
    {
        var (db, tenantContext, userService, hrService) = SetupTestEnvironment();
        var tenantId = Guid.NewGuid();

        // Employee 1
        var emp1 = new EmployeeProfile
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            UserId = "user-emp-1",
            EmployeeNumber = "EMP-001",
            FirstName = "Alice",
            LastName = "Smith"
        };

        // Employee 2
        var emp2 = new EmployeeProfile
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            UserId = "user-emp-2",
            EmployeeNumber = "EMP-002",
            FirstName = "Bob",
            LastName = "Jones"
        };

        db.Employees.AddRange(emp1, emp2);

        var leave1 = new LeaveRequest
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            RequestNumber = "LR-2026-0001",
            EmployeeId = emp1.Id,
            LeaveType = LeaveType.Annual,
            StartDateUtc = DateTime.UtcNow.Date.AddDays(2),
            EndDateUtc = DateTime.UtcNow.Date.AddDays(4),
            DaysCount = 3,
            Reason = "Trip",
            Status = LeaveStatus.Pending
        };

        var leave2 = new LeaveRequest
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            RequestNumber = "LR-2026-0002",
            EmployeeId = emp2.Id,
            LeaveType = LeaveType.Sick,
            StartDateUtc = DateTime.UtcNow.Date,
            EndDateUtc = DateTime.UtcNow.Date.AddDays(1),
            DaysCount = 2,
            Reason = "Medical",
            Status = LeaveStatus.Pending
        };

        db.LeaveRequests.AddRange(leave1, leave2);
        await db.SaveChangesAsync();

        // Switch to Employee 1
        tenantContext.SetContext(tenantId, "user-emp-1", TenantRole.Employee);
        userService.UserId = "user-emp-1";

        var emp1Leaves = await hrService.GetLeaveRequestsAsync(new LeaveRequestFilterRequest());

        emp1Leaves.Data.Should().HaveCount(1);
        emp1Leaves.Data[0].RequestNumber.Should().Be("LR-2026-0001");
        emp1Leaves.Data[0].EmployeeName.Should().Be("Alice Smith");

        // Attempting to view Employee 2's request by ID should throw ForbiddenAccessException
        var act = async () => await hrService.GetLeaveRequestByIdAsync(leave2.Id);
        await act.Should().ThrowAsync<ForbiddenAccessException>();
    }

    [Fact]
    public async Task Manager_CanViewAndApprove_DirectReportLeaveRequest()
    {
        var (db, tenantContext, userService, hrService) = SetupTestEnvironment();
        var tenantId = Guid.NewGuid();

        var manager = new EmployeeProfile
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            UserId = "user-mgr-1",
            EmployeeNumber = "MGR-001",
            FirstName = "Diana",
            LastName = "Prince",
            JobTitle = "Engineering Manager"
        };

        var report = new EmployeeProfile
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            UserId = "user-rep-1",
            EmployeeNumber = "EMP-101",
            FirstName = "Clark",
            LastName = "Kent",
            JobTitle = "Software Engineer",
            ReportsToEmployeeId = manager.Id
        };

        db.Employees.AddRange(manager, report);

        var leave = new LeaveRequest
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            RequestNumber = "LR-2026-0010",
            EmployeeId = report.Id,
            LeaveType = LeaveType.Annual,
            StartDateUtc = DateTime.UtcNow.Date.AddDays(10),
            EndDateUtc = DateTime.UtcNow.Date.AddDays(12),
            DaysCount = 3,
            Reason = "Vacation",
            Status = LeaveStatus.Pending
        };

        db.LeaveRequests.Add(leave);
        await db.SaveChangesAsync();

        // Set context to Manager
        tenantContext.SetContext(tenantId, "user-mgr-1", TenantRole.Manager);
        userService.UserId = "user-mgr-1";

        var result = await hrService.ActionLeaveRequestAsync(leave.Id, new ActionLeaveRequestRequest
        {
            Status = LeaveStatus.Approved
        });

        result.Status.Should().Be(LeaveStatus.Approved);
        result.ApproverEmployeeName.Should().Be("Diana Prince");
        result.ActionedAtUtc.Should().NotBeNull();
    }

