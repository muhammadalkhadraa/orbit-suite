    [Fact]
    public async Task CrossTenant_IsolationEnforced_CannotViewOtherTenantData()
    {
        var (db, tenantContext, userService, hrService) = SetupTestEnvironment();
        var tenantA = Guid.NewGuid();
        var tenantB = Guid.NewGuid();

        var empA = new EmployeeProfile
        {
            Id = Guid.NewGuid(),
            TenantId = tenantA,
            UserId = "user-admin-a",
            EmployeeNumber = "EMP-A",
            FirstName = "Admin",
            LastName = "TenantA"
        };

        var empB = new EmployeeProfile
        {
            Id = Guid.NewGuid(),
            TenantId = tenantB,
            UserId = "user-admin-b",
            EmployeeNumber = "EMP-B",
            FirstName = "Admin",
            LastName = "TenantB"
        };

        db.Employees.AddRange(empA, empB);

        var leaveA = new LeaveRequest
        {
            Id = Guid.NewGuid(),
            TenantId = tenantA,
            RequestNumber = "LR-2026-0001",
            EmployeeId = empA.Id,
            Reason = "Tenant A private leave",
            Status = LeaveStatus.Pending
        };

        var leaveB = new LeaveRequest
        {
            Id = Guid.NewGuid(),
            TenantId = tenantB,
            RequestNumber = "LR-2026-0002",
            EmployeeId = empB.Id,
            Reason = "Tenant B private leave",
            Status = LeaveStatus.Pending
        };

        db.LeaveRequests.AddRange(leaveA, leaveB);
        await db.SaveChangesAsync();

        // In Tenant A context
        tenantContext.SetContext(tenantA, "user-admin-a", TenantRole.Admin);
        userService.UserId = "user-admin-a";

        var tenantALeaves = await hrService.GetLeaveRequestsAsync(new LeaveRequestFilterRequest());
        tenantALeaves.Data.Should().ContainSingle(l => l.RequestNumber == "LR-2026-0001");
        tenantALeaves.Data.Should().NotContain(l => l.RequestNumber == "LR-2026-0002");
    }
