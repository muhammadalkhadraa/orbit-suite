    [Fact]
    public async Task Employee_CanCheckInAndCheckOut_CalculatingTotalHours()
    {
        var (db, tenantContext, userService, hrService) = SetupTestEnvironment();
        var tenantId = Guid.NewGuid();

        tenantContext.SetContext(tenantId, "user-emp-1", TenantRole.Employee);
        userService.UserId = "user-emp-1";

        var emp = new EmployeeProfile
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            UserId = "user-emp-1",
            EmployeeNumber = "EMP-001",
            FirstName = "Alice",
            LastName = "Smith"
        };

        db.Employees.Add(emp);
        await db.SaveChangesAsync();

        // 1. Check in
        var checkInResult = await hrService.CheckInAsync(new CheckInRequest
        {
            WorkLocation = "HQ Austin",
            Notes = "Arrived on time"
        });

        checkInResult.Should().NotBeNull();
        checkInResult.CheckInTimeUtc.Should().NotBeNull();
        checkInResult.CheckOutTimeUtc.Should().BeNull();
        checkInResult.WorkLocation.Should().Be("HQ Austin");
        checkInResult.Status.Should().Be(AttendanceStatus.Present);

        // 2. Check out
        var checkOutResult = await hrService.CheckOutAsync(new CheckOutRequest
        {
            Notes = "Completed shift"
        });

        checkOutResult.CheckOutTimeUtc.Should().NotBeNull();
        checkOutResult.TotalHours.Should().NotBeNull();
        checkOutResult.Notes.Should().Contain("Completed shift");
    }

